/**
 * 冻结数组与每一个条目。`readonly` 只在类型检查时生效，运行时仍能被调用方
 * `push`、`sort` 或改字段；冻结后任何修改在严格模式下直接抛错，目录不会被悄悄改掉。
 */
function freezeEntries<T extends object>(entries: T[]): readonly T[] {
  for (const entry of entries) {
    Object.freeze(entry);
  }
  return Object.freeze(entries);
}

